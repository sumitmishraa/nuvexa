// Pre-makes every image size so pages never wait on the runtime optimizer.
// Run with: node scripts/optimize-images.mjs
import fs from "node:fs";
import path from "node:path";
import sharp from "sharp";

const root = process.cwd();
const sets = [
  { from: "assets/photos", to: "public/media", url: "/media", widths: [384, 640, 1080, 1600, 2400] },
  { from: "assets/brands", to: "public/brands", url: "/brands", widths: [384, 640, 1080] },
];

const manifest = {};
for (const set of sets) {
  const dir = path.join(root, set.from);
  for (const name of fs.readdirSync(dir).filter((f) => /\.(webp|jpe?g)$/i.test(f))) {
    const base = name.replace(/\.[^.]+$/, "");
    const file = path.join(dir, name);
    const meta = await sharp(file).metadata();
    for (const width of set.widths) {
      await sharp(file)
        .resize({ width, withoutEnlargement: true })
        .webp({ quality: width >= 1600 ? 74 : 76, effort: 5 })
        .toFile(path.join(root, set.to, `${base}-${width}.webp`));
    }
    const blur = await sharp(file).resize({ width: 20 }).webp({ quality: 40 }).toBuffer();
    manifest[`${set.url}/${base}.webp`] = {
      ratio: Number((meta.width / meta.height).toFixed(3)),
      blur: `data:image/webp;base64,${blur.toString("base64")}`,
    };
    console.log(set.url, base);
  }
}

const body = Object.entries(manifest)
  .map(([key, value]) => `  ${JSON.stringify(key)}: ${JSON.stringify(value)},`)
  .join("\n");
fs.writeFileSync(
  path.join(root, "src/content/photo-manifest.ts"),
  `/* Generated by scripts/optimize-images.mjs. Do not edit by hand. */\nexport const photoManifest: Record<string, { ratio: number; blur: string }> = {\n${body}\n};\n`,
);
