// Pre-makes every image size so pages never wait on the runtime optimizer.
// Run with: node scripts/optimize-images.mjs
//
// Photo slots (src/content/photo-slots.json): each slot is its own file, cropped to the exact
// shape of its frame. A generated master in assets/gen/<slot>.png wins; otherwise the slot's
// stock fallback in assets/photos is used until the generated one arrives.
import fs from "node:fs";
import path from "node:path";
import sharp from "sharp";

const root = process.cwd();
const MEDIA_WIDTHS = [384, 640, 1080, 1600, 2400];
const slots = JSON.parse(fs.readFileSync(path.join(root, "src/content/photo-slots.json"), "utf8"));
// Video posters stay as plain masters, uncropped.
const posters = ["pipette-plate", "analyser-hall", "pipette-hood", "gloves-lab"];

const manifest = {};
const written = new Set();

async function emit({ file, base, url, outDir, widths, ratio, generated }) {
  const meta = await sharp(file).metadata();
  let width = meta.width;
  let height = meta.height;
  if (ratio && Math.abs(width / height - ratio) > 0.01) {
    if (width / height > ratio) width = Math.round(height * ratio);
    else height = Math.round(width / ratio);
  }
  // Crop to the frame's exact shape, keeping the most interesting part of the picture.
  const master = await sharp(file).resize({ width, height, fit: "cover", position: sharp.strategy.attention }).toBuffer();
  for (const w of widths) {
    const name = `${base}-${w}.webp`;
    await sharp(master)
      .resize({ width: w, withoutEnlargement: true })
      .webp({ quality: w >= 1600 ? 74 : 76, effort: 5 })
      .toFile(path.join(root, outDir, name));
    written.add(`${outDir}/${name}`);
  }
  const blur = await sharp(master).resize({ width: 20 }).webp({ quality: 40 }).toBuffer();
  manifest[`${url}/${base}.webp`] = {
    ratio: Number((width / height).toFixed(3)),
    blur: `data:image/webp;base64,${blur.toString("base64")}`,
    ...(generated !== undefined ? { generated } : {}),
  };
  console.log(url, base, generated === false ? "(fallback)" : "");
}

for (const [key, slot] of Object.entries(slots)) {
  const gen = ["png", "jpg", "jpeg", "webp"].map((ext) => path.join(root, "assets/gen", `${key}.${ext}`)).find((f) => fs.existsSync(f));
  const stock = fs.readdirSync(path.join(root, "assets/photos")).find((f) => f.replace(/\.[^.]+$/, "") === slot.fallback);
  const file = gen ?? path.join(root, "assets/photos", stock);
  await emit({ file, base: key, url: "/media", outDir: "public/media", widths: MEDIA_WIDTHS, ratio: slot.ratio, generated: Boolean(gen) });
}
for (const base of posters) {
  const file = fs.readdirSync(path.join(root, "assets/photos")).find((f) => f.replace(/\.[^.]+$/, "") === base);
  await emit({ file: path.join(root, "assets/photos", file), base, url: "/media", outDir: "public/media", widths: MEDIA_WIDTHS });
}
for (const name of fs.readdirSync(path.join(root, "assets/brands")).filter((f) => /\.webp$/i.test(f))) {
  await emit({ file: path.join(root, "assets/brands", name), base: name.replace(/\.webp$/, ""), url: "/brands", outDir: "public/brands", widths: [384, 640, 1080] });
}

// Remove served sizes that nothing uses any more.
for (const dir of ["public/media", "public/brands"]) {
  for (const name of fs.readdirSync(path.join(root, dir))) {
    if (/-\d+\.webp$/.test(name) && !written.has(`${dir}/${name}`)) fs.rmSync(path.join(root, dir, name));
  }
}

const body = Object.entries(manifest)
  .map(([key, value]) => `  ${JSON.stringify(key)}: ${JSON.stringify(value)},`)
  .join("\n");
fs.writeFileSync(
  path.join(root, "src/content/photo-manifest.ts"),
  `/* Generated by scripts/optimize-images.mjs. Do not edit by hand. */\nexport const photoManifest: Record<string, { ratio: number; blur: string; generated?: boolean }> = {\n${body}\n};\n`,
);
